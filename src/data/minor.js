export const MINOR = SUITS.flatMap((suit) =>
  RANKS.map((r, i) => {
    const [keywords, upright, reversed, yn] = TEXT[suit.id][i]
    return {
      key: `${suit.id}-${r.rank}`,
      arcana: 'minor',
      suit: suit.id,
      rank: r.rank,
      numeral: r.numeral,
      name: `${suit.ko} ${r.ko}`,
      en: `${r.en} of ${suit.en}`,
      symbol: r.court ?? suit.symbol,
      suitSymbol: suit.symbol,
      hue: suit.hue + (r.rank - 7) * 3,
      keywords,
      upright,
      reversed,
      yn,
    }
  }),
)

export const suitOf = (id) => SUITS.find((s) => s.id === id)
